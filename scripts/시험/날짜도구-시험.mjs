// 날짜 계산기 — 만 나이 · D-day · 며칠 뒤 · 영업일이 쓰는 «셈» 시험.
//
//   cd homepage
//   OB_ROOT="$PWD" node --experimental-strip-types --import ./scripts/시험/별칭.mjs ./scripts/시험/날짜도구-시험.mjs
//
// ★여기서 잡는 것은 전부 «조용히 틀리는» 종류다. 화면은 멀쩡히 뜨고 오류도 안 난다.
//   날짜는 하루가 어긋나도 아무도 눈치채지 못하다가, 남의 마감을 놓치게 만든다.

import { holidaysOf, holidayName, dowOf, 공휴일_범위 } from "@/lib/holidays";
import {
  krAge,
  span,
  addUnit,
  diffDays,
  isBusinessDay,
  쉬는이유,
  addBusinessDays,
  countBusinessDays,
  올바른날짜,
} from "@/lib/dates";

let 통과 = 0;
const 실패 = [];
const 같나 = (무엇, 실제, 기대) => {
  const a = JSON.stringify(실제);
  const b = JSON.stringify(기대);
  if (a === b) 통과 += 1;
  else 실패.push(`${무엇} — 기대 ${b} · 실제 ${a}`);
};

// ── 공휴일 표가 실제와 맞나 ─────────────────────────────────────
//
// ★여기 적은 것은 «실제로 그랬던 날»이다. 규칙 코드를 고치다 대체공휴일이
//   하루 밀리면 영업일 계산이 통째로 틀어지는데, 화면으로는 절대 안 보인다.

같나("2024 설날 대체 (2/11 일요일)", holidayName("2024-02-12"), "대체공휴일");
같나("2024 어린이날 대체 (5/5 일요일)", holidayName("2024-05-06"), "대체공휴일");
같나("2025 삼일절 대체 (3/1 토요일)", holidayName("2025-03-03"), "대체공휴일");
같나("2025 어린이날 = 부처님오신날", holidayName("2025-05-05"), "어린이날 · 부처님오신날");
같나("2025 그 대체", holidayName("2025-05-06"), "대체공휴일");
같나("2025 추석 대체 (10/5 일요일)", holidayName("2025-10-08"), "대체공휴일");
같나("2026 삼일절 대체", holidayName("2026-03-02"), "대체공휴일");
같나("2026 광복절 대체 (8/15 토요일)", holidayName("2026-08-17"), "대체공휴일");
같나("2026 개천절 대체 (10/3 토요일)", holidayName("2026-10-05"), "대체공휴일");
같나("2027 한글날 대체는 일요일을 건너뛴다", holidayName("2027-10-11"), "대체공휴일");
같나("2027 성탄절 대체", holidayName("2027-12-27"), "대체공휴일");
같나("2028 개천절이 추석과 겹쳐 생긴 대체", holidayName("2028-10-05"), "대체공휴일");

// ★대체가 «없어야» 하는 것들 — 있는 것보다 이쪽이 더 자주 틀린다
같나("추석이 토요일과 겹쳐도 대체는 없다 (2026)", holidayName("2026-09-28"), null);
같나("현충일은 일요일이어도 대체가 없다 (2027)", holidayName("2027-06-07"), null);
같나("신정은 토요일이어도 대체가 없다 (2028)", holidayName("2028-01-03"), null);
같나("근로자의 날은 관공서 공휴일이 아니다", holidayName("2026-05-01"), null);
같나("제헌절은 2008년부터 공휴일이 아니다", holidayName("2026-07-17"), null);

// ★표 밖의 해 — «공휴일 0일»로 조용히 답하면 안 된다
같나("표 밖의 해는 모른다고 한다", holidaysOf(공휴일_범위.끝 + 1).length, 0);
같나("표 밖의 날도 null", holidayName(`${공휴일_범위.끝 + 1}-01-01`), null);

// ── 날짜 자체 ───────────────────────────────────────────────────
같나("없는 날은 안 받는다 (2월 30일)", 올바른날짜("2026-02-30"), false);
같나("윤년 2월 29일은 있다", 올바른날짜("2024-02-29"), true);
같나("평년 2월 29일은 없다", 올바른날짜("2026-02-29"), false);
같나("형식이 아니면 안 받는다", 올바른날짜("2026-8-1"), false);
같나("요일 — 2026-08-26 은 수요일", dowOf("2026-08-26"), 3);

// ── ① 만 나이 ───────────────────────────────────────────────────
{
  const a = krAge("1990-05-10", "2026-05-09");
  같나("생일 하루 전이면 아직 안 먹었다", a.만, 35);
  같나("생일 하루 전 D-1", a.다음생일까지, 1);
}
{
  const a = krAge("1990-05-10", "2026-05-10");
  같나("생일 당일에 한 살 는다", a.만, 36);
  같나("생일 당일이면 다음 생일은 내년", a.다음생일, "2027-05-10");
  같나("연 나이", a.연, 36);
  같나("세는 나이", a.세는, 37);
}
같나("태어난 날은 0살", krAge("2026-08-26", "2026-08-26").만, 0);
같나("태어난 날은 1일째", krAge("2026-08-26", "2026-08-26").살아온일수, 1);
같나("아직 안 태어난 날은 못 센다", krAge("2027-01-01", "2026-08-26"), null);
같나("개월 — 만 1년 6개월", krAge("2025-01-10", "2026-07-10").개월, 18);
같나("개월 — 하루 모자라면 안 넘어간다", krAge("2025-01-10", "2026-07-09").개월, 17);

// ★2월 29일생 — 평년에는 생일이 없다. 법제처 해석대로 2월 28일에 한 살 는다
같나("2/29생, 평년 2/28 에 한 살", krAge("2000-02-29", "2026-02-28").만, 26);
같나("2/29생, 평년 2/27 은 아직", krAge("2000-02-29", "2026-02-27").만, 25);
같나("2/29생 윤년엔 2/29 에", krAge("2000-02-29", "2028-02-29").만, 28);
같나("2/29생은 화면에 알려 준다", krAge("2000-02-29", "2026-08-26").윤달생일주의, true);
같나("보통 생일은 안 알린다", krAge("1990-05-10", "2026-08-26").윤달생일주의, false);

// ── ② 날짜 사이 · D-day ─────────────────────────────────────────
같나("같은 날은 0일", diffDays("2026-08-26", "2026-08-26"), 0);
같나("윤년 2월을 넘어가도 맞다", diffDays("2024-02-28", "2024-03-01"), 2);
같나("평년 2월", diffDays("2026-02-28", "2026-03-01"), 1);

{
  const s = span("2026-08-26", "2026-08-26");
  같나("오늘이면 D-day", s.dday, "D-day");
  같나("«며칠째»는 1일째", s.포함일수, 1);
}
// ★사귄 지 100일 — 만난 날이 1일째다. 여기서 하루 어긋나면 아무도 안 믿는다
같나("100일은 99일 뒤", span("2026-01-01", "2026-04-10").포함일수, 100);
같나("지난 날은 D+", span("2026-08-26", "2026-08-20").dday, "D+6");
같나("앞날은 D-", span("2026-08-26", "2026-09-05").dday, "D-10");
{
  const s = span("2025-01-31", "2026-03-01");
  같나("년·월·일로 쪼갠 것", [s.년, s.월, s.일], [1, 1, 1]);
}
// ★월말이 낀 쪼개기 — 뺄셈으로 풀면 «일»이 음수로 남던 자리
{
  const m = (a, b) => { const s = span(a, b); return [s.년, s.월, s.일]; };
  같나("1/31 → 2/28 은 딱 1개월", m("2026-01-31", "2026-02-28"), [0, 1, 0]);
  같나("1/31 → 3/31 은 2개월", m("2026-01-31", "2026-03-31"), [0, 2, 0]);
  같나("윤년 2/29 → 평년 2/28 은 딱 1년", m("2024-02-29", "2025-02-28"), [1, 0, 0]);
  같나("거꾸로 넣어도 같게 쪼갠다", m("2026-03-01", "2025-01-31"), [1, 1, 1]);
}

같나("주와 나머지", [span("2026-08-01", "2026-08-20").주, span("2026-08-01", "2026-08-20").나머지일], [2, 5]);

// ── ③ 며칠 뒤는 언제 ────────────────────────────────────────────
같나("30일 뒤", addUnit("2026-08-26", 30, "일"), "2026-09-25");
같나("30일 전", addUnit("2026-08-26", -30, "일"), "2026-07-27");
같나("2주 뒤", addUnit("2026-08-26", 2, "주"), "2026-09-09");
// ★말일 처리 — 1월 31일 + 1개월이 «3월 3일»로 굴러가면 안 된다
같나("1/31 + 1개월 = 2월 말", addUnit("2026-01-31", 1, "개월"), "2026-02-28");
같나("윤년이면 2/29", addUnit("2024-01-31", 1, "개월"), "2024-02-29");
같나("3/31 + 1개월 = 4/30", addUnit("2026-03-31", 1, "개월"), "2026-04-30");
같나("윤년 2/29 + 1년 = 평년 2/28", addUnit("2024-02-29", 1, "년"), "2025-02-28");
같나("12개월 뒤는 1년 뒤", addUnit("2026-08-26", 12, "개월"), "2027-08-26");

// ── ④ 영업일 ────────────────────────────────────────────────────
같나("평일은 일한다", isBusinessDay("2026-08-26", "관공서"), true);
같나("토요일은 안 한다", isBusinessDay("2026-08-29", "관공서"), false);
같나("토요일도 일하는 곳은 한다", isBusinessDay("2026-08-29", "토요일도근무"), true);
같나("일요일은 어디든 안 한다", isBusinessDay("2026-08-30", "토요일도근무"), false);
같나("공휴일은 안 한다", isBusinessDay("2026-08-17", "관공서"), false);

// ★근로자의 날 — 관공서는 열고 은행은 닫는다. 한 기준만 두면 반드시 한쪽이 틀린다
같나("근로자의 날 — 관공서는 연다", isBusinessDay("2026-05-01", "관공서"), true);
같나("근로자의 날 — 은행은 닫는다", isBusinessDay("2026-05-01", "은행회사"), false);
같나("쉬는 이유를 그대로 말해 준다", 쉬는이유("2026-08-17", "관공서"), "대체공휴일");
같나("토요일 이유", 쉬는이유("2026-08-29", "관공서"), "토요일");
같나("일하는 날은 이유가 없다", 쉬는이유("2026-08-26", "관공서"), null);

// 「n 영업일 뒤」 — 기준일 다음 날부터 센다 (신청한 날은 안 센다)
같나("1영업일 뒤 (수→목)", addBusinessDays("2026-08-26", 1, "관공서").값, "2026-08-27");
같나("금요일의 1영업일 뒤는 월요일", addBusinessDays("2026-08-28", 1, "관공서").값, "2026-08-31");
같나("5영업일 뒤는 다음 주 같은 요일", addBusinessDays("2026-08-26", 5, "관공서").값, "2026-09-02");
// ★자동차 재검사 「10일 이내(토·일·공휴일 빼고)」 — 우리 케이스북이 실제로 쓰는 셈
같나("10영업일 뒤", addBusinessDays("2026-08-26", 10, "관공서").값, "2026-09-09");
// ★추석 연휴를 지나는 구간 — 9/24·25 공휴일, 9/26·27 주말
같나("추석을 건너뛴다", addBusinessDays("2026-09-23", 1, "관공서").값, "2026-09-28");
같나("건너뛴 날을 세어 준다", addBusinessDays("2026-09-23", 1, "관공서").쉰날.length, 4);
같나("거꾸로도 센다", addBusinessDays("2026-08-31", -1, "관공서").값, "2026-08-28");
같나("0영업일이면 제자리", addBusinessDays("2026-08-26", 0, "관공서").값, "2026-08-26");
같나("표 밖으로 나가면 알려 준다", addBusinessDays(`${공휴일_범위.끝}-12-30`, 5, "관공서").표밖, true);
같나("표 안이면 조용하다", addBusinessDays("2026-08-26", 5, "관공서").표밖, false);

// 두 날짜 사이 영업일 수
{
  const c = countBusinessDays("2026-08-24", "2026-08-28", "관공서").값; // 월~금, 공휴일 없음
  같나("월~금 그날 포함 5", c.그날포함, 5);
  같나("월~금 다음날부터 4", c.다음날부터, 4);
  같나("쉰 날 0", c.쉰날수, 0);
  같나("달력으로는 5일", c.달력일수, 5);
}
{
  // 2026-09-23(수) ~ 2026-09-30(수) — 24·25 추석, 26·27 주말
  const c = countBusinessDays("2026-09-23", "2026-09-30", "관공서").값;
  같나("추석 낀 주 — 일하는 날", c.그날포함, 4);
  같나("추석 낀 주 — 쉰 날", c.쉰날수, 4);
}
같나("거꾸로 넣어도 같게 센다", countBusinessDays("2026-08-28", "2026-08-24", "관공서").값.그날포함, 5);
같나("시작일이 쉬는 날이면 «다음날부터»가 안 깎인다",
  countBusinessDays("2026-08-29", "2026-09-02", "관공서").값.다음날부터, 3);
같나("너무 먼 구간은 안 센다", countBusinessDays("2020-01-01", "2040-01-01", "관공서"), null);

// ── 결과 ────────────────────────────────────────────────────────
console.log(`\n[날짜 계산기 시험] 통과 ${통과} · 실패 ${실패.length}`);
if (실패.length) {
  for (const f of 실패) console.log("  ✗ " + f);
  process.exit(1);
}
console.log("✓ 전부 통과.\n");
