//   상단 하위 탭·전체 목록·상세 화면이 한꺼번에 따라온다. 화면 코드는 안 고쳐도 된다.
//
// ★가격을 적지 않는다 (회사 공통 규칙 00-hq/policy.json).
//   파는 값은 판매 페이지에서만 말한다. 여기엔 «어디로 가면 살 수 있는가»만 둔다.

export interface ServiceCTA {
  label: string;
  href: string;
  /** primary = 채운 버튼(주 행동) · ghost = 테두리 버튼(보조) */
  kind: "primary" | "ghost";
  /** 바깥 사이트로 나가는 링크인가 */
  external?: boolean;
}

export interface ServiceDef {
  slug: string;
  /** 하위 탭에 쓰는 짧은 이름 */
  tab: string;
  /** 정식 이름 */
  name: string;
  emoji: string;
  /** 배너 맨 위 작은 글씨 */
  kicker: string;
  /** 배너 큰 제목 */
  headline: string;
  /** 배너 설명 */
  lead: string;
  /** 지금 상태 뱃지 — 사실만 적는다 */
  status: string;
  /** 상태 뱃지 색 (tailwind 클래스) */
  statusTone: string;
  ctas: ServiceCTA[];
  bgFrom: string;
  bgTo: string;
  /** 관련 글을 고를 열쇠말 — 글에 붙은 **태그**와 정확히 맞을 때만 인정한다 */
  keywords: string[];
  /**
   * 제목에 들어 있으면 그 서비스 글로 보는 **고유 이름**.
   * ★흔한 낱말(발표·화면·운세 같은 것)을 여기 넣지 말 것 —
   *   상관없는 기사가 서비스 안내 화면에 딸려 온다.
   */
  brandTerms: string[];
  /** 무엇이 좋은지 3~4칸 */
  highlights: { icon: string; title: string; desc: string }[];
  /** 검색엔진용 한 줄 */
  metaDesc: string;

  // ── 아래 넷은 선택 항목 (있는 서비스만 화면에 칸이 생긴다) ──
  /**
   * 화면에 보이는 사양표.
   * ★구조화 데이터(JSON-LD)와 «같은 값»을 쓴다.
   *   화면에 없는 것을 스키마에만 적으면 구글 규정 위반이다.
   */
  spec?: { label: string; value: string }[];
  /** 화면에 보이는 자주 묻는 질문 — FAQPage 스키마가 이 배열을 그대로 쓴다 */
  faqs?: { q: string; a: string }[];
  /** 링크 공유용 대표 이미지 (없으면 사이트 기본값 /og.png) */
  ogImage?: string;
  /** 대표 이미지 실제 크기 — 없는 값을 적으면 안 되므로 파일에서 잰 값을 넣는다 */
  ogImageSize?: { width: number; height: number };
  /** 검색엔진용 keywords (이 화면 전용) */
  metaKeywords?: string[];
}

