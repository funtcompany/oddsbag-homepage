// 오즈백 — 평서체(…한다) → 존댓말(…합니다) 바꾸기
//
// 왜 : 케이스북(data/casebook)은 «자료»라 «…한다» 로 적는 것이 맞다.
//      그런데 오즈백 글은 존댓말이다. 그대로 이어 붙이면
//      「내 갱신 기간을 조회한다입니다」 같은 문장이 나온다 (실제로 나왔다).
//      자료의 말투를 바꾸는 대신, 글로 «뽑을 때» 한 번 바꾼다.
//
// ★AI 를 쓰지 않는다. 한글 자모 계산으로 하는 규칙 변환이라 결과가 항상 같다.
//
// 규칙 (다 앞 글자의 받침을 본다)
//   받침 ㄴ  → ㅂ 으로 갈고 +니다      한다→합니다 · 걸린다→걸립니다 · 나온다→나옵니다
//   받침 ㄹ  → ㅂ 으로 갈고 +니다      만들다→만듭니다 · 안다→압니다
//   받침 없음 → ㅂ 을 붙이고 +니다     크다→큽니다 · 다르다→다릅니다 · 이다→입니다
//   앞 글자가 「는」 → 「습니다」        읽는다→읽습니다 · 붙는다→붙습니다
//   그 밖의 받침 → +습니다             있다→있습니다 · 없다→없습니다 · 낫다→낫습니다

const 시작 = 0xac00;
const 종성수 = 28;
const 중성수 = 21;

const 자모 = (ch) => {
  const code = ch.charCodeAt(0) - 시작;
  if (code < 0 || code > 11171) return null;
  return {
    초: Math.floor(code / (중성수 * 종성수)),
    중: Math.floor((code % (중성수 * 종성수)) / 종성수),
    종: code % 종성수,
  };
};
const 합자 = ({ 초, 중, 종 }) => String.fromCharCode(시작 + (초 * 중성수 + 중) * 종성수 + 종);

const 종ㄴ = 4;
const 종ㄹ = 8;
const 종ㅂ = 17;

// 받침 없이 끝나는 «그림씨(형용사)» 어간. 여기 없으면 이름씨+이다 로 본다.
//  늘릴 때는 반드시 시험(높임말-시험)에 짝을 함께 넣을 것.
const 어간끝 = [
  "하다", "크다", "르다", "쁘다", "프다", "쓰다", "흐리다", "느리다", "어리다",
  "드물다", "이르다", "고르다", "무디다", "지나다",
];

// 규칙에 안 맞는 것만 따로 적는다. 늘리기 전에 위 규칙으로 되는지 먼저 볼 것.
const 예외 = new Map([
  ["이다", "입니다"],
  ["아니다", "아닙니다"],
  ["그렇다", "그렇습니다"],
  ["어떻다", "어떻습니다"],
]);

/** 낱말 하나(…다 로 끝나는)를 존댓말로. 못 바꾸면 null 을 돌려준다 — 조용히 넘기지 않는다. */
export function 낱말바꾸기(말) {
  if (예외.has(말)) return 예외.get(말);
  if (!말.endsWith("다") || 말.length < 2) return null;

  const 앞 = 말.slice(0, -1);
  const 끝글자 = 앞[앞.length - 1];

  if (끝글자 === "는") return 앞.slice(0, -1) + "습니다";

  const j = 자모(끝글자);
  if (!j) return null;

  // ★받침 없는 글자 + 다 는 두 가지다. 가르지 않으면 「2종 소지자다」가
  //   「소지잡니다」가 된다 (실제로 그렇게 나왔다).
  //     · 형용사 어간   — 크다·바쁘다·다르다·필요하다 → ㅂ 을 붙여 「…ㅂ니다」
  //     · 이름씨 + 이다 — 소지자다·1매다·처음이다      → 「…입니다」
  //   평서체에서 «움직씨»는 -ㄴ다/-는다 로 끝나므로(간다·읽는다) 여기 오지 않는다.
  //   그래서 남는 것은 그림씨 아니면 잡음씨(이다)뿐이고, 그림씨만 적어 두면 갈린다.
  if (j.종 === 0) {
    // 「처음이다」처럼 잡음씨가 «이» 로 드러나 있으면 그 이를 먹고 입니다 가 된다.
    //  (그냥 붙이면 「처음이입니다」가 된다 — 시험에서 잡았다)
    if (끝글자 === "이" && 앞.length > 1) return 앞.slice(0, -1) + "입니다";
    const 그림씨 = 어간끝.some((끝) => 말.endsWith(끝));
    if (!그림씨) return 앞 + "입니다";
    return 앞.slice(0, -1) + 합자({ ...j, 종: 종ㅂ }) + "니다";
  }
  if (j.종 === 종ㄴ || j.종 === 종ㄹ) return 앞.slice(0, -1) + 합자({ ...j, 종: 종ㅂ }) + "니다";
  return 앞 + "습니다";
}

// 문장 끝의 «…다» 를 찾는다.
// ★띄어쓰기를 문장 끝으로 보면 안 된다 — 「통신사마다 따로」의 «마다» 가 걸려
//   「통신사마입니다 따로」가 된다. 실제로 그렇게 나왔다(2026-08-21).
//   조사 «마다·보다·부터·라다» 는 뒤에 말이 이어지므로, 진짜 끝(줄 끝·마침표)만 잡는다.
// ★줄표(— –) 앞도 문장 끝이다. 「조치 순서가 정해져 있다 — 지급정지…」의 앞머리가
//   안 바뀌어 글 한가운데에 평서체가 남았다(2026-08-21 검토에서 잡음).
const 문장끝 = /([가-힣]{1,12}다)(?=$|\n|[.!?)\]」』]|\s*[—–])/gm;

/** 글 한 덩이를 존댓말로. 못 바꾼 낱말은 그대로 두고 목록으로 함께 돌려준다. */
export function 존댓말(글) {
  const 못바꾼 = [];
  const 결과 = String(글).replace(문장끝, (m) => {
    const r = 낱말바꾸기(m);
    if (r === null) {
      못바꾼.push(m);
      return m;
    }
    return r;
  });
  return { 글: 결과, 못바꾼 };
}

/** 문장 끝이 아직 평서체로 남아 있는 줄을 찾아낸다 — 뽑은 뒤 검사용. */
export function 평서체남았나(글) {
  return String(글)
    .split("\n")
    .filter((줄) => /[가-힣]다[.]?\s*$/.test(줄.trim()) && !/습니다[.]?$|니다[.]?$/.test(줄.trim()));
}
