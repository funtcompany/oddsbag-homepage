/** 짧은 꿀팁 본문을 늘려 돌려준다. 실패하거나 오히려 짧아지면 null. */
export async function expandTipBody(post) {
  const user = `[늘릴 글]
제목: ${post.title}
요약: ${post.summary ?? ""}
본문:
${post.body}

위 글을 지침대로 더 자세히 다시 써라. 없는 사실은 절대 추가하지 마라.`;

  const raw = await ask(EXPAND_SYSTEM, user, { maxTokens: 4200, careful: true });
  const body = pick(raw, "body");
  if (!body) return null;
  if (hasBrokenChars(body)) return null;
  // 소제목이 사라졌거나 오히려 짧아졌으면 쓰지 않는다 (개악 방지)
  const heads = (s) => (s.match(/^## /gm) ?? []).length;
  if (heads(body) < heads(post.body)) return null;
  if (body.length < post.body.length * 1.25) return null;
  return body;
}

// 태그 형식 파서 — 본문에 줄바꿈/따옴표가 있어도 안전하다
export function pick(text, name) {
  const m = text.match(new RegExp(`<${name}>([\\s\\S]*?)</${name}>`, "i"));
  return m ? sanitize(m[1].trim()) : "";
}

// 글자 깨짐 검사 — 드물게 AI 응답에 깨진 문자가 섞여 들어온다.
// 이런 글이 그대로 발행되면 독자에게 '전�g이' 처럼 보인다.
const BROKEN = /[\uFFFD\uD800-\uDFFF]/; // 깨진 문자 · 짝 없는 서로게이트

export function hasBrokenChars(text) {
  return BROKEN.test(text);
}

// 보이지 않는 제어문자·특수 공백 정리 (한글/이모지/문장부호는 그대로 둔다)
export function sanitize(text) {
  return text
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, "") // 제어문자
    .replace(/[\u200B-\u200D\uFEFF\u2060]/g, "") // 폭 없는 공백 (복사할 때 깨짐 유발)
    .replace(/\u00A0/g, " ") // 안 보이는 특수 공백 → 일반 공백
    .replace(/[ \t]+\n/g, "\n")
    .trim();
}

