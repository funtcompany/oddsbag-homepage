// 오즈백 툴즈 — 다음에 뭘 낼지 «그 자리에서» 뽑는다
//
// 왜 : 기획안을 문서로 한 번 써 두면 그 목록이 떨어지는 순간 기획이 멈춘다.
//      목록이 아니라 «창고 + 뽑는 규칙»으로 둔다. 창고를 채우면 기획안은 저절로 나온다.
//
// ★AI 를 한 번도 안 부른다. 사람이 창고(data/tools-backlog.json)에 적어 둔 것을
//   관문에 걸고 점수로 줄 세울 뿐이다. 지어낼 여지가 없다.
// ★아무것도 고치지 않는다. 읽고 보여 주기만 한다.
//
// 쓰는 법 (반드시 homepage/ 에서)
//   node content-factory/툴즈-기획.mjs              다음에 낼 것 + 확인할 것
//   node content-factory/툴즈-기획.mjs --전체        떨어뜨린 것·낸 것까지
//   node content-factory/툴즈-기획.mjs --html=<경로> 사장님이 읽으실 기획안으로

import fs from "node:fs";
import path from "node:path";

const 값 = (이름, 기본 = "") => {
  const 앞 = `--${이름}=`;
  const 찾음 = process.argv.find((a) => a.startsWith(앞));
  return 찾음 === undefined ? 기본 : 찾음.slice(앞.length);
};
const 전체 = process.argv.includes("--전체");

const 창고경로 = path.join(process.cwd(), "data", "tools-backlog.json");
const 창고 = JSON.parse(fs.readFileSync(창고경로, "utf-8"));

// 관문 이름 ↔ 사람 말
const 관문말 = {
  돈: "돈이 안 든다",
  레디스: "레디스를 안 쓴다",
  검색: "찾는 사람이 있다",
  갑자기: "갑자기 필요해지는 것이다",
  연결: "이미 있는 것과 이어진다",
};

/** 관문을 못 넘은 것 목록 */
function 막힌관문(c) {
  if (!c.관문) return [];
  return Object.entries(c.관문)
    .filter(([, ok]) => ok === false)
    .map(([k]) => 관문말[k] ?? k);
}

/**
 * 점수 = 유입 × 연결 ÷ 품.
 * ★감으로 순서를 정하면 다음 사람이 뒤집는다. 셈으로 두면 «값을 고쳐서» 다툰다 — 그게 낫다.
 */
function 점수(c) {
  const 유입 = Number(c.유입) || 1;
  const 연결 = Number(c.연결) || 1;
  const 품 = Number(c.품) || 1;
  return Math.round(((유입 * 연결) / 품) * 10) / 10;
}

const 후보 = 창고.후보 ?? [];
const 낼수있음 = 후보.filter((c) => c.상태 === "낼수있음" && 막힌관문(c).length === 0)
  .sort((a, b) => 점수(b) - 점수(a));
const 확인필요 = 후보.filter((c) => c.상태 === "확인필요").sort((a, b) => 점수(b) - 점수(a));
const 떨어뜨림 = 후보.filter((c) => c.상태 === "떨어뜨림");
const 냈음 = 후보.filter((c) => c.상태 === "냈음");

// ★창고에 «관문에 걸리는데 낼수있음으로 적힌 것»이 있으면 그건 사람이 잘못 적은 것이다
const 어긋남 = 후보.filter((c) => c.상태 === "낼수있음" && 막힌관문(c).length > 0);

// ── 화면에 뿌리기 ──────────────────────────────────────────────
const 줄 = (s = "") => console.log(s);

줄(`\n[오즈백 툴즈 기획] 창고 갱신일 ${창고.갱신일} · 후보 ${후보.length}건`);
줄(`  낸 것 ${냈음.length} · 낼 수 있음 ${낼수있음.length} · 확인 필요 ${확인필요.length} · 떨어뜨림 ${떨어뜨림.length}`);

if (어긋남.length) {
  줄(`\n  ⚠ 창고가 어긋났다 — 관문에 걸리는데 «낼수있음»으로 적혀 있다`);
  for (const c of 어긋남) 줄(`     · ${c.name} — ${막힌관문(c).join(", ")} 에서 걸린다`);
}

줄(`\n■ 다음에 낼 것 (점수 = 유입 × 연결 ÷ 품)`);
if (!낼수있음.length) {
  줄("  없다. ★창고가 말랐다 — 아래 「후보를 어디서 더 찾나」를 보고 채운다.");
} else {
  낼수있음.forEach((c, i) => {
    줄(`\n  ${i + 1}. ${c.emoji} ${c.name}   점수 ${점수(c)}  (유입 ${c.유입} · 연결 ${c.연결} · 품 ${c.품})`);
    줄(`     ${c.한줄}`);
    if (c.검색어?.length) 줄(`     검색어 — ${c.검색어.join(" · ")}`);
    if (c.이어지는곳) 줄(`     이어짐 — ${c.이어지는곳}`);
    if (c.메모) 줄(`     메모 — ${c.메모}`);
  });
}

줄(`\n■ 확인이 끝나야 낼 수 있는 것`);
if (!확인필요.length) 줄("  없다.");
for (const c of 확인필요) {
  줄(`\n  · ${c.emoji} ${c.name}   점수 ${점수(c)}`);
  줄(`    확인할 것 — ${c.확인할것 ?? "(안 적혀 있다)"}`);
}

if (전체) {
  줄(`\n■ 떨어뜨린 것 (되살리려면 «떨어뜨린이유»가 먼저 풀려야 한다)`);
  for (const c of 떨어뜨림) {
    줄(`  · ${c.emoji} ${c.name} — ${c.떨어뜨린이유 ?? "(이유가 안 적혀 있다)"}`);
    if (막힌관문(c).length) 줄(`      막힌 관문: ${막힌관문(c).join(", ")}`);
  }
  줄(`\n■ 이미 낸 것`);
  for (const c of 냈음) 줄(`  · ${c.emoji} ${c.name}  (${c.낸날})`);
}

// ★창고가 마르기 «전에» 알려 준다. 마르고 나서 알면 이미 늦다.
if (낼수있음.length < 3) {
  줄(`\n⚠ 낼 수 있는 후보가 ${낼수있음.length}건뿐이다. 셋 아래로 내려가면 기획이 곧 멈춘다.`);
  줄(`  후보를 어디서 더 찾나:`);
  for (const w of 창고.후보를_어디서_더_찾나 ?? []) 줄(`    · ${w}`);
}

줄(`\n창고 — ${path.relative(process.cwd(), 창고경로)}`);
줄(`후보를 넣으려면 이 파일에 한 칸 적으면 된다. 관문 다섯을 다 적어야 여기 뜬다.\n`);

// ── 사장님이 읽으실 기획안(마크다운) ───────────────────────────
const html경로 = 값("html");
if (html경로) {
  const 표 = (rows) => rows.join("\n");
  const md = `# 오즈백 툴즈 — 지금 시점 기획안

> 이 문서는 \`content-factory/툴즈-기획.mjs\` 가 창고(\`data/tools-backlog.json\`)를 읽어 그 자리에서 만든 것입니다.
> **문서를 고치지 마십시오** — 창고를 고치고 다시 뽑으면 됩니다.
> 창고 갱신일 ${창고.갱신일} · 후보 ${후보.length}건

## 지금 낼 수 있는 것

점수는 **유입 × 연결 ÷ 품**입니다. 감이 아니라 셈이라, 순서가 마음에 안 들면 값을 고치면 됩니다.

| 순 | 도구 | 점수 | 한 줄 | 이어지는 곳 |
|---|---|---|---|---|
${표(낼수있음.map((c, i) => `| ${i + 1} | ${c.emoji} **${c.name}** | ${점수(c)} | ${c.한줄} | ${c.이어지는곳 ?? "-"} |`))}

## 확인이 끝나야 낼 수 있는 것

${확인필요.length ? 표(확인필요.map((c) => `- ${c.emoji} **${c.name}** — ${c.확인할것 ?? ""}`)) : "없습니다."}

## 떨어뜨린 것

${떨어뜨림.length ? 표(떨어뜨림.map((c) => `- ${c.emoji} **${c.name}** — ${c.떨어뜨린이유 ?? ""}`)) : "없습니다."}

## 이미 낸 것 ${냈음.length}개

${표(냈음.map((c) => `- ${c.emoji} ${c.name} (${c.낸날})`))}

## 후보가 마르지 않게 — 어디서 더 찾나

${표((창고.후보를_어디서_더_찾나 ?? []).map((w) => `- ${w}`))}

${낼수있음.length < 3 ? `\n> ⚠ **낼 수 있는 후보가 ${낼수있음.length}건뿐입니다.** 셋 아래면 기획이 곧 멈춥니다.\n` : ""}
`;
  fs.mkdirSync(path.dirname(html경로), { recursive: true });
  fs.writeFileSync(html경로, md);
  줄(`✓ 기획안 → ${html경로}`);
  줄(`  (보기 좋게: node "00-hq/tools/보기좋게.mjs" ${html경로})\n`);
}
